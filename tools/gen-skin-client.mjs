/**
 * Generate the skin's client plugin source from the Harness personal theme.
 *
 * The window runtime (drag, resize, click-to-front layering, cascade, composer
 * reserve, docks) lives in the Harness checkout as a personal patch to
 * `@deepseek-ai/dsh-client-ui-theme`. This skin ships the same runtime as a
 * standalone client plugin, so the code is extracted from the marked block
 * rather than hand-copied — otherwise the two copies drift.
 *
 * Usage:
 *   node tools/gen-skin-client.mjs [path/to/harness/checkout]
 *
 * Writes src/client/index.ts. Run `node build.mjs` afterwards to produce the
 * shipped lib/client.js.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SKIN_ROOT = resolve(HERE, '..')

/** The marked region inside the Harness theme's client entry. */
const START = '/* >>> arcade-window-runtime >>>'
const END = '/* <<< arcade-window-runtime <<< */'

/** Default Harness checkout: the skin is developed beside it. */
const DEFAULT_HARNESS = 'C:\\Users\\USER\\Documents\\Codex\\2026-08-14\\deepseek-harness'

const harnessRoot = resolve(process.argv[2] ?? process.env.DSH_HARNESS_ROOT ?? DEFAULT_HARNESS)
const source = join(harnessRoot, 'packages', 'client', 'ui-theme', 'src', 'client', 'index.ts')

let text
try {
  text = readFileSync(source, 'utf8')
} catch (error) {
  console.error(`gen-skin-client: cannot read the Harness client entry:\n  ${source}`)
  console.error('Pass the Harness checkout path: node tools/gen-skin-client.mjs <harness-root>')
  console.error(String(error?.message ?? error))
  process.exit(1)
}

const start = text.indexOf(START)
const end = text.indexOf(END)
if (start === -1 || end === -1 || end <= start) {
  console.error(`gen-skin-client: the marked runtime block is missing from ${source}.`)
  console.error(`Expected both "${START}" and "${END}".`)
  process.exit(1)
}

// The start sentinel is a multi-line block comment: skip past its closing
// marker so the generated file carries runtime code only.
const startCommentEnd = text.indexOf('*/', start)
if (startCommentEnd === -1) {
  console.error('gen-skin-client: the start sentinel comment is not terminated.')
  process.exit(1)
}
const body = text.slice(startCommentEnd + 2, text.lastIndexOf('\n', end)).trim()

if (!body.includes('ARCADE_RUNTIME_INSTALLERS')) {
  console.error('gen-skin-client: extracted block does not carry the installer roster.')
  process.exit(1)
}

const header = `/**
 * Rizen Signal Console — window runtime, client half.
 *
 * GENERATED by tools/gen-skin-client.mjs from the Harness personal theme
 * (packages/client/ui-theme/src/client/index.ts). Do not edit by hand:
 * change the source block there and re-run \`npm run gen && npm run build\`.
 *
 * The runtime is pure DOM code with no Harness imports. It gives every detail
 * surface — Think, tool output, Code — free placement, edge resizing,
 * click-to-front layering and cascade, while leaving the conversation column
 * exactly as wide as it was.
 */

`

const shell = `
/**
 * Page-global install marker, shared verbatim with the Harness personal theme
 * patch. Both bundles may be present (a developer running the patched checkout
 * plus this skin); the page is the only place they can coordinate, so whichever
 * installs second stands down instead of doubling every document listener.
 */
const ARCADE_RUNTIME_FLAG = '__dshArcadeWindowRuntime'

/** Cordis plugin name. */
export const name = 'dsh-skin-digital-arcade-windows'

/** The runtime needs no Harness services: it observes the DOM directly. */
export const inject = []

/**
 * Mount the window runtime, once per page.
 * @param ctx - client plugin context providing \`effect\`.
 */
export function apply(ctx) {
  const host = globalThis
  if (host[ARCADE_RUNTIME_FLAG] === true) return
  host[ARCADE_RUNTIME_FLAG] = true
  ctx.effect(() => {
    const disposers = ARCADE_RUNTIME_INSTALLERS.map(install => install())
    return () => {
      for (const dispose of disposers) dispose()
      delete host[ARCADE_RUNTIME_FLAG]
    }
  }, 'dsh-skin-digital-arcade: window runtime')
}
`

const outDir = join(SKIN_ROOT, 'src', 'client')
mkdirSync(outDir, { recursive: true })
const outFile = join(outDir, 'index.ts')
writeFileSync(outFile, `${header}${body}\n${shell}`, 'utf8')

const lines = body.split('\n').length
console.log(`gen-skin-client: read    ${source}`)
console.log(`gen-skin-client: wrote   ${outFile}`)
console.log(`gen-skin-client: runtime ${lines} lines extracted`)
